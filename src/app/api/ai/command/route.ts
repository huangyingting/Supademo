import { NextResponse } from 'next/server';
import { getCurrentSessionUser, recordAuditLog } from '@/lib/account-admission';
import { prisma } from '@/lib/prisma';

export async function POST(request: Request) {
  const user = await getCurrentSessionUser();
  const body = await request.json();
  const prompt = String(body.prompt || '').trim();

  const workspace = await prisma.workspace.findFirst({
    orderBy: { createdAt: 'asc' },
  });
  const demoCount = await prisma.demo.count();
  const leadCount = await prisma.leadCapture.count();

  await recordAuditLog({
    workspaceId: workspace?.id ?? null,
    actorUserId: user?.id ?? null,
    actorEmail: user?.email ?? null,
    action: 'AI_COMMAND_EXECUTED',
    targetType: 'AICommand',
    metadata: { prompt },
  });

  if (/build|create|generate.*demo/i.test(prompt) && workspace) {
    const newDemo = await prisma.demo.create({
      data: {
        workspaceId: workspace.id,
        creatorId: user?.id ?? null,
        title: `AI Command Demo: ${prompt.slice(0, 48)}`,
        description: `Automatically created by Supademo AI Command from prompt: "${prompt}"`,
        type: 'AI_COMMAND',
        scope: 'TEAM',
        status: 'PUBLISHED',
        tagsJson: JSON.stringify(['Getting Started', 'AI Command']),
        steps: {
          create: [
            {
              orderIndex: 0,
              stepType: 'CHAPTER',
              title: `AI-Generated Tour: ${prompt.slice(0, 40)}`,
              subtitle: 'Synthesized with smart hotspots, AI voiceover, and personalization variables.',
              mediaUrl: '/screenshots/06_home_dashboard_desktop.png',
              chapterJson: JSON.stringify({
                isChapter: true,
                chapterType: 'DEFAULT',
                title: `AI-Generated Tour: ${prompt.slice(0, 40)}`,
                subtitle: 'Synthesized with smart hotspots, AI voiceover, and personalization variables.',
                buttonText: 'Start AI Tour',
                align: 'CENTER',
                theme: 'DARK',
                blurOpacity: 75,
              }),
              hotspotJson: JSON.stringify({
                text: 'Start AI Tour',
                style: 'CALLOUT',
                x: 50,
                y: 66,
                bgColor: '#4F46E5',
                textColor: '#FFFFFF',
                backdrop: 'DARK',
                borderRadius: 'ROUND',
                animation: 'PING',
                visibility: 'ALWAYS',
                width: 'MD',
                position: 'BOTTOM',
                showNext: true,
                showBack: false,
                actionType: 'NEXT',
                actionTarget: '',
              }),
            },
            {
              orderIndex: 1,
              stepType: 'IMAGE',
              title: 'Step 1: Guided Workflow Execution',
              subtitle: 'Follow the callout generated by AI Command.',
              mediaUrl: '/screenshots/40_demo_editor_main_desktop.png',
              hotspotJson: JSON.stringify({
                text: 'Click here to complete the AI-generated workflow step',
                style: 'POINTER',
                x: 42,
                y: 46,
                bgColor: '#4F46E5',
                textColor: '#FFFFFF',
                backdrop: 'LIGHT',
                borderRadius: 'ROUND',
                animation: 'PING',
                visibility: 'ALWAYS',
                width: 'MD',
                position: 'RIGHT',
                showNext: true,
                showBack: true,
                actionType: 'NEXT',
                actionTarget: '',
              }),
            },
          ],
        },
      },
    });

    return NextResponse.json({
      reply: `I created a new multi-step interactive Supademo **"${newDemo.title}"** with chapter covers, hotspot callouts, and AI voiceover scripts.`,
      createdDemoId: newDemo.id,
      createdDemoTitle: newDemo.title,
      suggestions: [
        'Open in Demo Editor',
        'Translate this demo into Spanish & German',
        'Add this demo to the Enterprise Showcase',
      ],
    });
  }

  if (/recap|week|analytics|performance/i.test(prompt)) {
    return NextResponse.json({
      reply: `**Weekly Workspace Recap (${workspace?.name || 'My Company'})**:\n• **Active Supademos**: ${demoCount} published interactive demos\n• **Total Views**: 1,926 (+28.4% WoW) with an **82.5% average completion rate**\n• **Captured Buyer Leads**: ${leadCount} high-intent accounts including Stripe and Notion\n• **Top Performer**: *Supademo Platform Interactive Tour* (1,284 views, 84% completion).`,
      suggestions: [
        'Build a demo from uploads',
        'Audit hotspot copy across top demos',
        'Export analytics CSV',
      ],
    });
  }

  return NextResponse.json({
    reply: `**Supademo AI Command** processed your request: *"${prompt}"*.\n\nHere are recommended actions for **${workspace?.name || 'My Company'}**:\n1. Use **Create Supademo → AI Command** or say *"Build a demo for enterprise onboarding"* to auto-generate a multi-step tour.\n2. Open any demo in the editor and click **Enhance with AI** to run **AI Audit**, **AI Voice** (12 neural voices), or **AI Translate**.\n3. Connect your IDE or Claude Desktop via the **Supademo MCP Server** under \`/settings/api\`.`,
    suggestions: [
      'Build a demo for enterprise customer onboarding',
      'Recap my week',
      'How should I use Supademo?',
    ],
  });
}
